#!/usr/bin/env bash
# Build the 6 core scion-frontiers/agent-team templates into factory/templates/
# directly from upstream https://github.com/scion-frontiers/agent-team at AGENT_TEAM_SHA.
#
# Each template uses the upstream agent-team role files:
#   - agents.md        = factory/team/team-rules.md (+ roles/coordinator.md for coordinator)
#                        + upstream templates/<role>/agents.md
#   - system-prompt.md = upstream templates/<role>/system-prompt.md
#   - scion-agent.yaml = harness/model/caps + upstream skills (pinned to AGENT_TEAM_SHA)
set -euo pipefail
# shellcheck source=infra/lib.sh
source "$(dirname "$0")/lib.sh"

UP="${REPO_ROOT}/.cache/agent-team-${AGENT_TEAM_SHA:0:7}"
OUT="${REPO_ROOT}/factory/templates"
TEAM="${REPO_ROOT}/factory/team"

IMPECCABLE="mount:impeccable"
ROLES=(
  "coordinator|coordinator|claude|large|||-|Project coordinator (acme-lead) — runs the factory loop, delegates work, merges autonomously"
  "eng-manager|eng-manager|claude|large|4h|800|-|Engineering manager — orchestrates multi-phase development and reviews under the coordinator"
  "architect|architect|antigravity|large|1h|200|-|Architect — produces design documents and ADRs before implementation (Gemini 4 Argon)"
  "developer|developer|claude|medium|2h|400|${IMPECCABLE}|Developer — implements backend/frontend features, fixes bugs, writes tests (Claude Sonnet 5.5 + impeccable)"
  "code-reviewer|code-reviewer|antigravity|large|45m|150|-|Code reviewer — evaluates PRs across correctness, architecture, security, and tests (Gemini 4 Argon)"
  "test-engineer|test-engineer|antigravity|medium|1h|200|-|Test engineer — designs test suites, scenario e2e tests, and guardrail checks (Gemini 3.8 Flash)"
)

fetch() {
  local dest="${UP}/$1/$2"
  [[ -s "${dest}" ]] && return 0
  mkdir -p "${UP}/$1"
  gh api "repos/scion-frontiers/agent-team/contents/templates/$1/$2?ref=${AGENT_TEAM_SHA}" -q .content \
    | base64 -d > "${dest}"
}

vendor_skill() {
  local name="$1" dest="$2" cache="${REPO_ROOT}/.cache/impeccable-${IMPECCABLE_SHA:0:7}"
  [[ "${name}" == impeccable ]] || { echo "unknown mounted skill ${name}" >&2; return 1; }
  if [[ ! -f "${cache}/.claude/skills/impeccable/SKILL.md" ]]; then
    rm -rf "${cache}"; git init -q "${cache}"
    git -C "${cache}" remote add origin https://github.com/pbakaus/impeccable.git
    git -C "${cache}" sparse-checkout set --no-cone .claude/skills/impeccable LICENSE NOTICE.md
    git -C "${cache}" fetch -q --depth 1 origin "${IMPECCABLE_SHA}"
    git -C "${cache}" checkout -q FETCH_HEAD
  fi
  rm -rf "${dest:?}/impeccable"; mkdir -p "${dest}"
  cp -R "${cache}/.claude/skills/impeccable" "${dest}/impeccable"
  cp "${cache}/LICENSE" "${dest}/impeccable/LICENSE"
  cp "${cache}/NOTICE.md" "${dest}/impeccable/NOTICE.md"
  printf 'Vendored from https://github.com/pbakaus/impeccable/tree/%s/.claude/skills/impeccable (Apache-2.0)\nby infra/40-build-team-templates.sh. Do not edit.\n' "${IMPECCABLE_SHA}" > "${dest}/impeccable/VENDORED.txt"
}

for spec in "${ROLES[@]}"; do
  IFS='|' read -r role upstream harness model maxdur maxturns extraskill desc <<<"${spec}"
  for f in agents.md system-prompt.md scion-agent.yaml; do fetch "${upstream}" "${f}"; done
  dir="${OUT}/${role}"; mkdir -p "${dir}"
  attribution="<!-- Generated by infra/40-build-team-templates.sh from scion-frontiers/agent-team@${AGENT_TEAM_SHA}/templates/${upstream} (Apache-2.0) -->"

  {
    echo "${attribution}"
    echo
    if [[ -f "${TEAM}/roles/${role}.md" ]]; then
      cat "${TEAM}/roles/${role}.md"
      echo
    elif [[ "${role}" == "developer" ]]; then
      echo "## UI Note: When touching frontend code, use the mounted \`impeccable\` skill for UI design, accessibility, and critique passes."
      echo
    fi
    cat "${TEAM}/team-rules.md"
    echo
    echo "---"
    echo
    cat "${UP}/${upstream}/agents.md"
  } > "${dir}/agents.md"
  { echo "${attribution}"; echo; cat "${UP}/${upstream}/system-prompt.md"; } > "${dir}/system-prompt.md"

  {
    echo "# Generated by infra/40-build-team-templates.sh — edit the generator, not this file."
    echo 'schema_version: "1"'
    echo "description: \"${desc}\""
    echo "agent_instructions: agents.md"
    echo "system_prompt: system-prompt.md"
    echo "default_harness_config: ${harness}"
    echo "model: ${model}"
    if [[ -n "${maxdur}" ]]; then echo "max_duration: \"${maxdur}\""; fi
    if [[ -n "${maxturns}" ]]; then
      echo "max_turns: ${maxturns}"
      echo "max_model_calls: $(( maxturns * 3 ))"
    fi
    upstream_env="$(awk '/^env:/{f=1;next} f&&/^[^ #]/{f=0} f&&/^  [A-Z_]+:/' "${UP}/${upstream}/scion-agent.yaml")"
    if [[ -n "${upstream_env}" || "${harness}" == "claude" ]]; then
      echo "env:"
      if [[ -n "${upstream_env}" ]]; then echo "${upstream_env}"; fi
      if [[ "${harness}" == "claude" ]]; then
        echo "  ANTHROPIC_DEFAULT_HAIKU_MODEL: claude-haiku-5-5"
      fi
    fi
    # Upstream skills list, with scion-frontiers/agent-team URIs pinned to AGENT_TEAM_SHA.
    up_skills="$(sed -n '/^skills:/,$p' "${UP}/${upstream}/scion-agent.yaml" \
      | sed -E "s|(gh://scion-frontiers/agent-team/[a-z0-9-]+)\"|\1@${AGENT_TEAM_SHA}\"|g")"
    if [[ -n "${up_skills}" ]]; then echo "${up_skills}"; fi
  } > "${dir}/scion-agent.yaml"
  if [[ "${extraskill}" == mount:* ]]; then vendor_skill "${extraskill#mount:}" "${dir}/skills"; fi
  echo "built ${dir#"${REPO_ROOT}/"} (${harness}/${model}, upstream ${upstream})"
done
